# student/auto_tuner.py
import json
import os
import subprocess
import itertools
from typing import Dict, Any

# 1. Hàm chạy benchmark thông qua CLI của project
def run_benchmark(num_seeds: int = 20, start_seed: int = 1000, total_time_sec: float = 60.0, output_json: str = "results/temp_tune.json") -> Dict[str, Any]:
    cmd = [
        "python", "scripts/benchmark_agent.py",
        "--agent", "student.agent:Agent",
        "--seeds", str(num_seeds),
        "--start-seed", str(start_seed),
        "--total-time-sec", str(total_time_sec),
        "--output", output_json
    ]
    
    # Gọi tiến trình chạy benchmark
    subprocess.run(cmd, check=True)
    
    # Đọc kết quả JSON xuất ra
    with open(output_json, "r", encoding="utf-8") as f:
        data = json.load(f)
    return data

# 2. Hàm cập nhật trọng số vào student/weights.py
def update_weights_file(weights: Dict[str, float]):
    content = f"# Generated by auto_tuner.py\nBEST_WEIGHTS = {json.dumps(weights, indent=4)}\n"
    with open("student/weights.py", "w", encoding="utf-8") as f:
        f.write(content)

# 3. Vòng lặp Grid Search thử nghiệm bộ trọng số
def grid_search():
    # Định nghĩa các dải giá trị cần thử nghiệm
    # Cách 2: Full Coarse Grid Search (243 tổ hợp - Quét rộng hơn)
# Dùng khi muốn thử nghiệm cả độ lớn của ma trận snake
    param_grid = {
    "snake": [1.0, 5.0, 10.0],
    "empty": [0.5, 1.5, 3.0],
    "corner_penalty": [0.5, 2.0, 5.0],
    "monotonicity": [0.5, 1.0, 2.0],
    "smoothness": [0.1, 0.5, 1.0]
    }

# Tổng số tổ hợp: 3 × 3 × 3 × 3 × 3 = 243 bộ trọng số
    keys, values = zip(*param_grid.items())
    permutations = [dict(zip(keys, v)) for v in itertools.product(*values)]
    
    best_score = -1.0
    best_params = None

    print(f"Bắt đầu Tuning {len(permutations)} bộ trọng số...")

    for i, params in enumerate(permutations):
        print(f"\n--- Thử nghiệm bộ trọng số {i+1}/{len(permutations)}: {params} ---")
        
        # Ghi trọng số mới vào weights.py
        update_weights_file(params)
        
        # Chạy thử nhanh với 5 seed để lọc trước
        results = run_benchmark(num_seeds=5, start_seed=100, total_time_sec=60.0)
        
        # Kiểm tra điều kiện QA (illegal_moves & exceptions)
        total_illegal = sum(r.get("illegal_moves", 0) for r in results.get("results", []))
        total_exceptions = sum(r.get("exceptions", 0) for r in results.get("results", []))
        
        if total_illegal > 0 or total_exceptions > 0:
            print(f"Bỏ qua bộ trọng số do vi phạm quy định (Illegal: {total_illegal}, Exceptions: {total_exceptions})")
            continue
            
        avg_score = results.get("summary", {}).get("mean_score", 0.0)
        print(f"-> Official Score trung bình (5 seeds): {avg_score}")
        
        if avg_score > best_score:
            best_score = avg_score
            best_params = params

    print("\n==========================================")
    print(f"Bộ trọng số tối ưu nhất: {best_params} với Điểm trung bình: {best_score}")
    
    # Ghi lại bộ trọng số tốt nhất thu được
    if best_params:
        update_weights_file(best_params)

if __name__ == "__main__":
    grid_search()